BASIS_RE = re.compile(r"(法|条例|办法|规定|官网|年|制度|准则)")


def with_basis(ana):
    """概念类解析没有具体出处的，补一句「依据类型」，让读者知道该条依据什么。"""
    if BASIS_RE.search(ana):
        return ana
    return ana + "（依据：金融基础概念与银行业务通识）"


